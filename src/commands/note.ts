import type { Command } from "commander";
import { isMap } from "yaml";
import { CliError } from "../lib/errors.ts";
import { emit, success } from "../lib/output.ts";
import { bold, dim, muted, table, warn } from "../lib/style.ts";
import { zodIssues, loadSong, saveSongDoc } from "../model/io.ts";
import { PPQ, drumName, pitchName, positionTicks } from "../model/music.ts";
import { InstrumentNote, VocalNote } from "../model/song.ts";
import type { LoadedSong } from "../model/io.ts";
import { notesSeq, parseIndices, parseJsonInput, sortNotes, trackIndex } from "./edit-helpers.ts";

interface NoteRow {
  /** Position in the track's `notes` array; null for notes generated by `arrange`. */
  index: number | null;
  at: string;
  beat: number;
  pitch: string;
  midi: number;
  dur: number;
  lyric: string | null;
  velocity: number | null;
}

function noteRows(loaded: LoadedSong, ti: number, includeGenerated = false): NoteRow[] {
  const track = loaded.compiled.tracks.find((t) => t.index === ti)!;
  const grid = loaded.compiled.grid;
  const drums = track.kind === "instrument" && track.program === "drums";
  return track.notes.filter((n) => includeGenerated || n.index >= 0).map((n) => ({
    index: n.index >= 0 ? n.index : null,
    at: grid.label(n.tick),
    beat: n.tick / PPQ,
    pitch: (drums && drumName(n.midi)) || pitchName(n.midi),
    midi: n.midi,
    dur: n.dur / PPQ,
    lyric: "lyric" in n ? n.lyric : null,
    velocity: "velocity" in n ? (n.velocity ?? null) : null,
  }));
}

function renderRows(rows: NoteRow[]): string {
  if (rows.length === 0) return muted("(no notes)");
  const hasLyrics = rows.some((r) => r.lyric !== null);
  return table(rows, [
    { header: "#", get: (r) => muted(r.index === null ? "gen" : String(r.index)), align: "right" },
    { header: "at", get: (r) => r.at },
    { header: "pitch", get: (r) => bold(r.pitch) },
    { header: "dur", get: (r) => `${r.dur}` + dim("q"), align: "right" },
    ...(hasLyrics
      ? [{ header: "lyric", get: (r: NoteRow) => r.lyric ?? muted("—") }]
      : [{ header: "vel", get: (r: NoteRow) => muted(String(r.velocity ?? "")), align: "right" as const }]),
  ]);
}

function asArray(value: unknown): Record<string, unknown>[] {
  const list = Array.isArray(value) ? value : [value];
  if (!list.every((v) => v && typeof v === "object" && !Array.isArray(v))) {
    throw new CliError({ code: "INVALID_ARGUMENT", message: "--params must be a JSON object or an array of objects" });
  }
  return list as Record<string, unknown>[];
}

interface NoteFlags {
  track?: string;
  params?: string;
  at?: string;
  pitch?: string;
  dur?: string;
  lyric?: string;
  velocity?: string;
  dryRun?: boolean;
}

function noteFromFlags(f: NoteFlags): Record<string, unknown> {
  const missing = (["at", "pitch", "dur"] as const).filter((k) => f[k] === undefined);
  if (missing.length) {
    throw new CliError({
      code: "MISSING_ARGUMENT",
      message: `Missing --${missing.join(", --")} (or pass --params with a JSON note/array)`,
    });
  }
  const num = (v: string) => (/^-?\d+(\.\d+)?$/.test(v) ? Number(v) : v);
  const note: Record<string, unknown> = { at: num(f.at!), pitch: num(f.pitch!), dur: num(f.dur!) };
  if (f.lyric !== undefined) note.lyric = f.lyric;
  if (f.velocity !== undefined) note.velocity = Number(f.velocity);
  return note;
}

export function registerNote(program: Command): void {
  const note = program.command("note").description("List, add, edit and delete notes on a track");

  note
    .command("list")
    .description("List a track's notes with index, position, pitch, duration (quarter notes) and lyric")
    .argument("[dir]", "song directory or song.yaml", ".")
    .option("--track <id>", "track id (optional if the song has one track)")
    .option("--from <pos>", 'start position, e.g. "9:1"')
    .option("--to <pos>", "end position (exclusive)")
    .option("--generated", "include notes generated by `arrange` (index null)")
    .action(async (dir: string, opts: { track?: string; from?: string; to?: string; generated?: boolean }) => {
      const loaded = await loadSong(dir);
      const ti = trackIndex(loaded, opts.track);
      const grid = loaded.compiled.grid;
      const toTick = (v: string) => positionTicks(/^\d+(\.\d+)?$/.test(v) ? Number(v) : v, grid);
      const from = opts.from ? toTick(opts.from) : 0;
      const to = opts.to ? toTick(opts.to) : Number.POSITIVE_INFINITY;
      const rows = noteRows(loaded, ti, opts.generated).filter((r) => r.beat * PPQ >= from && r.beat * PPQ < to);
      emit({ data: rows, human: renderRows });
    });

  note
    .command("add")
    .description("Add one or more notes. Use --params with a JSON note or array for batches")
    .argument("[dir]", "song directory or song.yaml", ".")
    .option("--track <id>", "track id (optional if the song has one track)")
    .option("--params <json>", 'note object or array, e.g. \'[{"at":"5:1","pitch":"A4","dur":"1/8","lyric":"ら"}]\'')
    .option("--at <pos>", 'position: "bar:beat" or quarter notes')
    .option("--pitch <pitch>", "e.g. C5, F#4, or MIDI number")
    .option("--dur <dur>", 'quarter notes or fraction, e.g. 0.5 or "1/8"')
    .option("--lyric <text>", "lyric for vocal tracks")
    .option("--velocity <n>", "1-127 for instruments")
    .option("--dry-run", "validate and show the result without writing")
    .action(async (dir: string, opts: NoteFlags) => {
      const loaded = await loadSong(dir);
      const ti = trackIndex(loaded, opts.track);
      const track = loaded.data.tracks[ti]!;
      // --params wins over sugar flags when both are present (documented precedence).
      const incoming = opts.params ? asArray(parseJsonInput("--params", opts.params)) : [noteFromFlags(opts)];
      const schema = track.kind === "vocal" ? VocalNote : InstrumentNote;
      incoming.forEach((n, i) => {
        const r = schema.safeParse(n);
        if (!r.success) {
          throw new CliError({
            code: "INVALID_NOTE",
            message: `Note ${i} does not match the ${track.kind} note schema`,
            details: zodIssues(r.error).map((d) => ({ ...d, path: `[${i}].${d.path}` })),
            hint: track.kind === "vocal" ? "Vocal notes need at, pitch, dur and lyric" : "Instrument notes need at, pitch and dur",
          });
        }
      });
      const seq = notesSeq(loaded.doc, ti);
      const added = new WeakSet<object>();
      for (const n of incoming) {
        const node = loaded.doc.createNode(n, { flow: true });
        added.add(node);
        seq.add(node);
      }
      sortNotes(seq, loaded.compiled.grid);
      const newIndices = seq.items.flatMap((item, i) => (added.has(item as object) ? [i] : []));
      const saved = await saveSongDoc(loaded.file, loaded.dir, loaded.doc, { dryRun: opts.dryRun });
      const rows = noteRows(saved, ti).filter((r) => r.index !== null && newIndices.includes(r.index));
      emit({
        data: { dryRun: Boolean(opts.dryRun), track: track.id, added: rows, noteCount: saved.compiled.tracks.find((t) => t.index === ti)!.notes.length },
        warnings: saved.warnings,
        human: (d) => `${d.dryRun ? warn("dry run — nothing written") : success(`Added ${d.added.length} note(s) to ${bold(d.track)}`)}\n${renderRows(d.added)}`,
        nextSteps: opts.dryRun ? [] : [`vocaloid render ${dir} --only ${track.id}`],
      });
    });

  note
    .command("edit")
    .description("Change fields of notes by index, e.g. --set '{\"pitch\":\"D5\"}'")
    .argument("[dir]", "song directory or song.yaml", ".")
    .option("--track <id>", "track id (optional if the song has one track)")
    .requiredOption("--index <list>", "note indices: 3, 3,5 or 3-7 (from `vocaloid note list`)")
    .requiredOption("--set <json>", "fields to set; null removes a field")
    .option("--dry-run", "validate and show the result without writing")
    .action(async (dir: string, opts: { track?: string; index: string; set: string; dryRun?: boolean }) => {
      const loaded = await loadSong(dir);
      const ti = trackIndex(loaded, opts.track);
      const patch = parseJsonInput("--set", opts.set);
      if (!patch || typeof patch !== "object" || Array.isArray(patch)) {
        throw new CliError({ code: "INVALID_ARGUMENT", message: "--set must be a JSON object" });
      }
      const seq = notesSeq(loaded.doc, ti);
      const indices = parseIndices(opts.index, seq.items.length);
      const before = noteRows(loaded, ti).filter((r) => r.index !== null && indices.includes(r.index));
      for (const i of indices) {
        const node = seq.items[i];
        if (!isMap(node)) continue;
        for (const [k, v] of Object.entries(patch)) {
          if (v === null) node.delete(k);
          else node.set(k, loaded.doc.createNode(v, { flow: true }));
        }
      }
      // Indices stay as given: re-sorting after an edit would renumber notes under the caller.
      const saved = await saveSongDoc(loaded.file, loaded.dir, loaded.doc, { dryRun: opts.dryRun });
      const after = noteRows(saved, ti).filter((r) => r.index !== null && indices.includes(r.index));
      emit({
        data: { dryRun: Boolean(opts.dryRun), track: loaded.data.tracks[ti]!.id, before, after },
        warnings: saved.warnings,
        human: (d) => `${d.dryRun ? warn("dry run — nothing written") : success(`Edited ${d.after.length} note(s)`)}\n${renderRows(d.after)}`,
      });
    });

  note
    .command("delete")
    .description("Delete notes by index or by position range")
    .argument("[dir]", "song directory or song.yaml", ".")
    .option("--track <id>", "track id (optional if the song has one track)")
    .option("--index <list>", "note indices: 3, 3,5 or 3-7")
    .option("--from <pos>", "delete notes starting at or after this position")
    .option("--to <pos>", "…and before this position")
    .option("--dry-run", "show what would be deleted without writing")
    .action(async (dir: string, opts: { track?: string; index?: string; from?: string; to?: string; dryRun?: boolean }) => {
      const loaded = await loadSong(dir);
      const ti = trackIndex(loaded, opts.track);
      const rows = noteRows(loaded, ti);
      let indices: number[];
      if (opts.index) {
        indices = parseIndices(opts.index, notesSeq(loaded.doc, ti).items.length);
      } else if (opts.from || opts.to) {
        const grid = loaded.compiled.grid;
        const toTick = (v: string) => positionTicks(/^\d+(\.\d+)?$/.test(v) ? Number(v) : v, grid);
        const from = opts.from ? toTick(opts.from) : 0;
        const to = opts.to ? toTick(opts.to) : Number.POSITIVE_INFINITY;
        indices = rows.filter((r) => r.index !== null && r.beat * PPQ >= from && r.beat * PPQ < to).map((r) => r.index!);
      } else {
        throw new CliError({ code: "MISSING_ARGUMENT", message: "Pass --index or --from/--to" });
      }
      const removed = rows.filter((r) => r.index !== null && indices.includes(r.index));
      const seq = notesSeq(loaded.doc, ti);
      for (const i of [...indices].sort((a, b) => b - a)) seq.items.splice(i, 1);
      await saveSongDoc(loaded.file, loaded.dir, loaded.doc, { dryRun: opts.dryRun });
      emit({
        data: { dryRun: Boolean(opts.dryRun), track: loaded.data.tracks[ti]!.id, removed },
        human: (d) => `${d.dryRun ? warn("dry run — nothing written") : success(`Deleted ${d.removed.length} note(s)`)}\n${renderRows(d.removed)}`,
        nextSteps: opts.dryRun ? [] : ["vocaloid undo"],
      });
    });
}
