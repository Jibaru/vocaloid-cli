import { stringify } from "yaml";
import type { CompiledSong, CompiledVocalTrack } from "../model/compile.ts";
import type { CurveName } from "../model/song.ts";

/**
 * OpenUtau project (.ustx, YAML). Verified against OpenUtau.Core (stakira/OpenUtau, ustx 0.9 loader).
 * Track gain/pan are left neutral here: stems are mixed by ffmpeg so every engine shares one mixer.
 */

export const USTX_VERSION = "0.9";

const CURVE_ABBR: Record<CurveName, string> = {
  dynamics: "dyn",
  pitchBend: "pitd",
  breathiness: "brec",
  gender: "genc",
  tension: "tenc",
  voicing: "voic",
};

/** Our curves are -100..100 for dynamics; OpenUtau's dyn is -240..120. */
function curveValue(name: CurveName, value: number): number {
  if (name === "dynamics") return Math.round(value < 0 ? value * 2.4 : value * 1.2);
  return Math.round(value);
}

function rendererFor(track: CompiledVocalTrack): Record<string, string> {
  return track.voice.type === "diffsinger"
    ? { renderer: "DIFFSINGER" }
    : { renderer: "CLASSIC", resampler: "worldline", wavtool: "convergence" };
}

function lyricFor(lyric: string, phonemes?: string): string {
  // OpenUtau reads a bracketed phonetic hint after the lyric, e.g. "ka[k a]".
  return phonemes ? `${lyric}[${phonemes}]` : lyric;
}

export function toUstx(song: CompiledSong, opts: { trackIds?: string[] } = {}): string {
  const vocals = song.tracks.filter(
    (t): t is CompiledVocalTrack =>
      t.kind === "vocal" && (!opts.trackIds || opts.trackIds.includes(t.id)),
  );

  const project = {
    name: song.title,
    comment: "Generated by @jibaru/vocaloid-cli",
    output_dir: "Vocal",
    cache_dir: "UCache",
    ustx_version: USTX_VERSION,
    resolution: 480,
    bpm: song.tempos[0]?.bpm ?? 120,
    beat_per_bar: song.timeSignatures[0]?.numerator ?? 4,
    beat_unit: song.timeSignatures[0]?.denominator ?? 4,
    exp_primary: 0,
    exp_secondary: 1,
    key: 0,
    time_signatures: song.timeSignatures.map((s) => ({
      bar_position: s.bar - 1,
      beat_per_bar: s.numerator,
      beat_unit: s.denominator,
    })),
    tempos: song.tempos.map((t) => ({ position: t.tick, bpm: t.bpm })),
    tracks: vocals.map((t) => {
      const phonemizer = t.voice.phonemizers[t.language as keyof typeof t.voice.phonemizers];
      return {
        singer: t.voice.singerId,
        phonemizer,
        renderer_settings: rendererFor(t),
        track_name: t.name,
        track_color: "Blue",
        mute: false,
        solo: false,
        volume: 0,
        pan: 0,
        voice_color_names: [""],
      };
    }),
    voice_parts: vocals.map((t, trackNo) => {
      const last = t.notes.at(-1);
      return {
        name: t.name,
        comment: "",
        track_no: trackNo,
        position: 0,
        duration: last ? last.tick + last.dur : 0,
        notes: t.notes.map((n) => {
          const expressions: { index: number; abbr: string; value: number }[] = [];
          const color = n.voiceColor ?? t.voiceColor;
          if (color) {
            expressions.push({ index: 0, abbr: "clr", value: t.voice.voiceColors.indexOf(color) });
          }
          if (n.velocity !== undefined) expressions.push({ index: 0, abbr: "vel", value: n.velocity });
          const vib = n.vibrato;
          return {
            position: n.tick,
            duration: n.dur,
            tone: n.midi,
            lyric: lyricFor(n.lyric, n.phonemes),
            pitch: {
              data: [
                { x: -40, y: 0, shape: "io" },
                { x: 40, y: 0, shape: "io" },
              ],
              snap_first: true,
            },
            vibrato: {
              length: vib?.length ?? 0,
              period: vib?.period ?? 175,
              depth: vib?.depth ?? 25,
              in: vib?.fadeIn ?? 10,
              out: vib?.fadeOut ?? 10,
              shift: 0,
              drift: 0,
              vol_link: 0,
            },
            phoneme_expressions: expressions,
            phoneme_overrides: [],
          };
        }),
        curves: (Object.entries(t.curves) as [CurveName, { tick: number; value: number }[]][])
          .filter(([, pts]) => pts.length > 0)
          .map(([name, pts]) => ({
            xs: pts.map((p) => p.tick),
            ys: pts.map((p) => curveValue(name, p.value)),
            abbr: CURVE_ABBR[name],
          })),
      };
    }),
    wave_parts: [],
  };

  return stringify(project, { lineWidth: 0 });
}
